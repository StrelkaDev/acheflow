"""Build the inspectable WASM text reactor; no native Twitch mapping is used."""
import json
from pathlib import Path
rules=[]
def rule(condition,*effects): rules.append((condition,effects))
def http(event_id,path,body=None,query=None):
    return {'type':'http','id':event_id,'method':'POST' if body else 'GET','url':'https://api.twitch.tv/helix/'+path,'body':body,'query':query or {}}
def viewers(): return http('viewers','streams',query={'user_id':'$/config/channel_id'})
rule({'/type':'start'},{'type':'websocket','url':'wss://eventsub.wss.twitch.tv/ws','resume':False},viewers())
rule({'/type':'tick'},viewers())
welcome={'/type':'websocket','/payload/metadata/message_type':'session_welcome','/resuming':False}
subscriptions=[]
for kind in ('channel.chat.message','channel.chat.message_delete','channel.chat.clear'):
    subscriptions.append(http('subscribe','eventsub/subscriptions',{'type':kind,'version':'1','condition':{'broadcaster_user_id':'$/config/channel_id','user_id':'$/config/user_id'},'transport':{'method':'websocket','session_id':'$/payload/payload/session/id'}}))
rule(welcome,*subscriptions)
rule({'/type':'websocket','/payload/metadata/message_type':'session_welcome'},{'type':'heartbeat','seconds':'$/payload/payload/session/keepalive_timeout_seconds'})
rule({'/type':'websocket','/payload/metadata/message_type':'session_reconnect'},{'type':'websocket','url':'$/payload/payload/session/reconnect_url','resume':True})
rule({'/type':'websocket','/payload/metadata/message_type':'revocation'},{'type':'failure','message':'Twitch revoked the chat subscription. Reconnect your account.'})
rule({'/type':'websocket','/payload/metadata/message_type':'notification','/payload/metadata/subscription_type':'channel.chat.message'},
 {'type':'chat','message':{'platform':'twitch','channel_id':'$/payload/payload/event/broadcaster_user_id','message_id':'$/payload/payload/event/message_id','user_id':'$/payload/payload/event/chatter_user_id','display_name':'$/payload/payload/event/chatter_user_name','text':'$/payload/payload/event/message/text','roles':{'$map':['$/payload/payload/event/badges','/set_id']},'occurred_at_ms':'$/now_ms'}})
for kind in ('message_delete','clear'):
    rule({'/type':'websocket','/payload/metadata/message_type':'notification','/payload/metadata/subscription_type':'channel.chat.'+kind},{'type':'delete','platform':'twitch','channel_id':'$/payload/payload/event/broadcaster_user_id','message_id':'$/payload/payload/event/message_id','all':kind=='clear'})
rule({'/type':'http_result','/id':'viewers','/payload/data':[]},{'type':'audience','sample':{'platform':'twitch','channel_id':'$/config/channel_id','stream_id':None,'observed_at_ms':'$/now_ms','concurrent':None,'offline':True,'unique':None}})
# An absent pointer compares equal to nothing, so the non-empty case is selected
# by a positive source marker inserted through a generic JSON-array guard.
rule({'/type':'http_result','/id':'viewers','/payload/data/0':{'$exists':True}},{'type':'audience','sample':{'platform':'twitch','channel_id':'$/config/channel_id','stream_id':'$/payload/data/0/id','observed_at_ms':'$/now_ms','concurrent':'$/payload/data/0/viewer_count','offline':False,'unique':None}})
rule({'/type':'send'},http('send','chat/messages',{'broadcaster_id':'$/channel_id','sender_id':'$/config/user_id','message':'$/text'}))
rule({'/type':'http_result','/id':'send'},{'type':'delivery','sent':'$/payload/data/0/is_sent'})

segments=[]; funcs=[]; offset=0
def data(value):
    global offset
    raw=json.dumps(value,separators=(',',':')).encode(); ptr=offset;offset+=len(raw)
    escaped=''.join('\\%02x'%b for b in raw)
    segments.append(f'  (data (i32.const {ptr}) "{escaped}")')
    return f'i32.const {ptr} i32.const {len(raw)}'
for condition,effects in rules:
    test=data(condition)
    emits='\n'.join('      '+data(effect)+' call $emit' for effect in effects)
    funcs.append(f'    {test} call $matches\n    if\n{emits}\n    end')
wat=''';; Generated by build_guest.py. Both conditions and platform mappings execute in WASM.
(module
  (import "acheflow" "matches" (func $matches (param i32 i32) (result i32)))
  (import "acheflow" "emit" (func $emit (param i32 i32)))
  (memory (export "memory") 1)
'''+ '\n'.join(segments)+'\n  (func (export "handle")\n'+'\n'.join(funcs)+'\n  )\n)\n'
Path(__file__).with_name('twitch.wat').write_text(wat)
